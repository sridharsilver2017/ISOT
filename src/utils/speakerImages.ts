/**
 * Normalizes a speaker name for lookup in the photo map
 */
export function normalizeSpeakerName(name: string): string {
  if (!name) return '';
  return name
    .trim()
    .replace(/^(Dr\.?|Prof\.?|Padma Shri|Padmashri|Padma Bhushan)\s+/i, '')
    .replace(/\s+/g, ' ')
    .trim();
}

/**
 * Returns the photo URL for a speaker name if available.
 * Checks dynamic uploaded photos first, then static registry.
 */
export function getSpeakerPhoto(
  name: string,
  dynamicPhotos?: Record<string, string>
): string | null {
  if (!name) return null;
  const trimmed = name.trim();
  const normalized = normalizeSpeakerName(trimmed);

  // 1. Dynamic uploaded photos from R2 / D1
  if (dynamicPhotos) {
    const slug = normalized.toLowerCase().replace(/[^a-z0-9]+/g, '-');
    if (dynamicPhotos[slug]) return dynamicPhotos[slug];
    if (dynamicPhotos[trimmed]) return dynamicPhotos[trimmed];
    if (dynamicPhotos[normalized]) return dynamicPhotos[normalized];
  }

  // 2. Exact match in static map
  if (SPEAKER_IMAGE_MAP[trimmed]) {
    return SPEAKER_IMAGE_MAP[trimmed];
  }

  // 3. Normalized match
  if (SPEAKER_IMAGE_MAP[normalized]) {
    return SPEAKER_IMAGE_MAP[normalized];
  }

  // 4. Case-insensitive lookup
  const lowerTrimmed = trimmed.toLowerCase();
  const lowerNormalized = normalized.toLowerCase();
  for (const [key, val] of Object.entries(SPEAKER_IMAGE_MAP)) {
    const kLower = key.toLowerCase();
    if (kLower === lowerTrimmed || kLower === lowerNormalized) {
      return val;
    }
  }

  return null;
}
